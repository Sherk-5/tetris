void clear_screen()
{
    printf("\033[2J"); // clears current visible terminal screen
    printf("\033[3J"); // clears scrollback buffer
    printf("\033[H"); // move cursor to top left;
    fflush(stdout);
}

void paint_bg_black()
{
    printf("\033[30m"); // preto
    for(int y = 0; y < HEIGHT; y++)
    {
        for(int x = 0 ; x < WIDTH; x++)
            printf("██");
        printf("\n");
    }
    printf("\033[0m"); // reset color
    fflush(stdout);
}

void draw_in_pos(int x, int y,char* s)
{
    int nx = x*2 - 1;
    printf("\033[%d;%dH", y, nx);
    printf("%s", s);
}

void draw_matrix()
{
    printf("\033[37m"); // branco
    for(int y = 0 ; y < 22 ; y++)
    {
        for(int x = 0 ; x < 12 ; x++)
        {
            switch (matrix[y][x])
            {
            case 'e':
                draw_in_pos(x + 2, y + 2, "  ");
                break;

            case 'f':
                draw_in_pos(x + 2, y + 2, "██");
                break;

            case 'l':
                draw_in_pos(x + 2, y + 2, "▌▐");
                break;

            case 'b':
                draw_in_pos(x + 2, y + 2, "▄▄");
                break;
            
            default:
                break;
            }
        }
    }
    printf("\033[0m"); // reset color

    fflush(stdout); // display this int this instant
}

void draw_frame()
{
    printf("\033[H"); // move cursor to top left

    paint_bg_black();
    draw_matrix();

    printf("\033[33m"); // amarelo
    draw_in_pos(posx+2, posy+2, "██"); // quadrado para testar input

    printf("\033[?25l"); fflush(stdout); // hides cursor
}

